// Builds supabase/ops/setup.sql: every migration, in order, in one file you can paste into the Supabase SQL editor
// (for when the Supabase CLI is not available). `npm run build:sql` writes it; a test fails if the committed copy is stale.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dir = resolve(root, 'supabase/migrations');

export function buildSetupSql() {
  const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
  const parts = files.map((f) => `-- ==== ${f} ====\n\n${readFileSync(resolve(dir, f), 'utf8').trimEnd()}\n`);
  return [
    '-- GENERATED by scripts/build-setup-sql.mjs from supabase/migrations. Do not edit by hand.',
    '-- Installs the whole schema in one go. For a project that had the old CountyConnect schema, run reset-connect.sql first.',
    '-- Run in a fresh SQL editor tab; it is safe to run once, and will stop with an error if anything already exists.',
    '',
    ...parts,
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(resolve(root, 'supabase/ops/setup.sql'), buildSetupSql());
  console.log('wrote supabase/ops/setup.sql');
}
