-- Public / Citizens Policies
CREATE POLICY "Anyone can view open tenders" ON public.tenders FOR SELECT USING (true);
CREATE POLICY "Anyone can view departments" ON public.departments FOR SELECT USING (true);
CREATE POLICY "Users can view their notifications" ON public.notifications FOR SELECT USING (auth.uid() = user_id OR user_id IS NULL);
CREATE POLICY "Users can update their notifications" ON public.notifications FOR UPDATE USING (auth.uid() = user_id);
CREATE POLICY "Anyone can view health drugs" ON public.health_drugs FOR SELECT USING (true);
CREATE POLICY "Anyone can view welfare programs" ON public.welfare FOR SELECT USING (true);
CREATE POLICY "Anyone can view petitions" ON public.petitions FOR SELECT USING (true);
CREATE POLICY "Anyone can vote on petitions" ON public.petitions FOR UPDATE USING (true);
CREATE POLICY "Anyone can view land records" ON public.land_records FOR SELECT USING (true);
